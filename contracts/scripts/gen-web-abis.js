// Writes app/src/generated/abis.ts from the compiled contracts, so the site always uses their exact ABIs (and can
// name their errors). Run after `npx hardhat compile`.
const fs = require("fs");
const path = require("path");

const ART = path.join(__dirname, "..", "artifacts", "src");
const OUT = path.join(__dirname, "..", "..", "app", "src", "generated", "abis.ts");
const list = [
  ["vaultAbi", "StockpoolVault.sol/StockpoolVault.json"],
  ["creditDeskAbi", "StockpoolCreditDesk.sol/StockpoolCreditDesk.json"],
  ["basketAbi", "StockpoolBasket.sol/StockpoolBasket.json"],
  ["oracleAbi", "StockpoolOracle.sol/StockpoolOracle.json"],
  ["positionAbi", "v4/StockpoolPosition.sol/StockpoolPosition.json"],
  ["buyBurnAbi", "StockpoolBuyBurn.sol/StockpoolBuyBurn.json"],
];
let ts = "// Generated by contracts/scripts/gen-web-abis.js from contracts/artifacts. Do not edit.\n";
for (const [name, file] of list) {
  const { abi } = JSON.parse(fs.readFileSync(path.join(ART, file), "utf8"));
  ts += `\nexport const ${name} = ${JSON.stringify(abi)} as const;\n`;
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, ts);
console.log(`Wrote ${path.relative(process.cwd(), OUT)}`);
